#!/usr/bin/env python3
"""Voice an episode script with Kokoro TTS and emit narration + captions + timing markers.

usage: KOKORO_DIR=<dir with kokoro-v1.0.onnx & voices-v1.0.bin> python3 tools/narrate.py episodes/<ep>
script.txt: one sentence per line. ' | ' splits caption chunks. '{name}' at a chunk start records a marker.
            '@0.5' at line end = pause after (s). '=' lines: display replacements "spoken => shown".
"""
import os, re, sys, json, subprocess
import numpy as np
from kokoro_onnx import Kokoro

ep = sys.argv[1]
kd = os.environ.get('KOKORO_DIR')
k = Kokoro(os.path.join(kd, 'kokoro-v1.0.onnx'), os.path.join(kd, 'voices-v1.0.bin'))
VOICE, SPEED, LANG = os.environ.get('VOICE', 'bm_george'), float(os.environ.get('SPEED', '1.0')), 'en-gb'

lines, repl = [], []
for raw in open(os.path.join(ep, 'script.txt')):
    raw = raw.rstrip('\n')
    if not raw.strip() or raw.startswith('#'): continue
    if raw.startswith('='):
        a, b = raw[1:].split('=>'); repl.append((a.strip(), b.strip())); continue
    m = re.search(r'@([\d.]+)\s*$', raw)
    pause = float(m.group(1)) if m else 0.4
    lines.append((raw[:m.start()].strip() if m else raw.strip(), pause))

def show(s):
    for a, b in repl: s = s.replace(a, b)
    return s

def syll(w):
    w = re.sub(r'[^a-z0-9]', '', w.lower())
    if w.isdigit(): return max(1, len(w))
    return max(1, len(re.findall(r'[aeiouy]+', w)))

SR = 24000
audio = [np.zeros(int(0.6 * SR), np.float32)]
t = 0.6
captions, markers = [], {}
for text, pause in lines:
    chunks = [c.strip() for c in text.split(' | ')]
    names = []
    clean = []
    for c in chunks:
        mm = re.match(r'\{(\w+)\}\s*', c)
        names.append(mm.group(1) if mm else None)
        clean.append(c[mm.end():] if mm else c)
    spoken = ' '.join(clean)
    samples, sr = k.create(spoken, voice=VOICE, speed=SPEED, lang=LANG)
    assert sr == SR
    s = np.asarray(samples, np.float32)
    # trim silence
    thr = 0.01 * np.abs(s).max()
    idx = np.where(np.abs(s) > thr)[0]
    s = s[max(0, idx[0] - int(0.03 * SR)): idx[-1] + int(0.06 * SR)]
    dur = len(s) / SR
    # distribute time over chunks/words by syllables (+ small comma weight)
    wts = []
    for c in clean:
        ws = c.split()
        wts.append([syll(w) + (0.6 if w.endswith((',', '.', '?', '!')) else 0) for w in ws])
    tot = sum(sum(w) for w in wts)
    cur = t
    for c, wl, nm in zip(clean, wts, names):
        if nm: markers[nm] = round(cur, 3)
        disp = show(c).rstrip(',.').replace(',', '').replace('...', '')
        dw = disp.split()
        sw = c.split()
        # word start times (spoken words); map onto display words proportionally
        starts, acc = [], cur
        for w in wl: starts.append(acc); acc += dur * w / tot
        if len(dw) == len(sw): ts = starts
        else: ts = [starts[min(len(starts) - 1, int(i * len(starts) / len(dw)))] for i in range(len(dw))]
        captions.append([round(cur, 2), ' '.join(dw), [round(x, 2) for x in ts]])
        cur = acc
    audio.append(s); audio.append(np.zeros(int(pause * SR), np.float32))
    t += dur + pause

full = np.concatenate(audio)
full = full / np.abs(full).max() * 0.89
pcm = (full * 32767).astype('<i2').tobytes()
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(SR), '-ac', '1', '-i', '-',
                '-af', 'highpass=f=70,acompressor=threshold=0.1:ratio=2.5:attack=10:release=150,loudnorm=I=-15:TP=-2:LRA=7',
                '-ar', '48000', '-c:a', 'aac', '-b:a', '160k', os.path.join(ep, 'narration.m4a')], input=pcm, check=True)
total = round(t + 0.6, 2)
with open(os.path.join(ep, 'captions.js'), 'w') as f:
    f.write("// Generated by tools/narrate.py — word-timed captions\n'use strict';\nconst CAPTIONS = [\n")
    for c in captions: f.write('  ' + json.dumps(c) + ',\n')
    f.write('];\n')
    f.write('const T = ' + json.dumps(markers, indent=1) + ';\n')
    f.write(f'const NARRATION_END = {total};\n')
print('duration', total, 'markers', len(markers))
